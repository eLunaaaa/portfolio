#!/usr/bin/env python3
# UART 수집 데이터의 wet/dry 로지스틱 회귀 학습 도구입니다.
# CSV 검증→feature 정규화→gradient descent→C 헤더 내보내기로 Python과 Master 추론을 연결합니다.

"""Train a small logistic-regression wet/dry classifier and export a C header."""

import argparse
import csv
import math
from pathlib import Path

import numpy as np


# 기능: UART 수집 CSV를 로지스틱 회귀 학습 배열로 읽습니다.
# 입력: path: H/UMB/HMEAN/DH/LABEL 열을 가진 CSV.
# 출력: feature float32 배열과 label 배열, 유효 데이터·두 클래스가 없으면 ValueError.
# 처리 구조: 값·범위·이진 label과 DH 일관성을 검사해 행을 선별하고 MCU 추론과 같은 feature 정규화를 적용합니다.
def load_dataset(path: Path) -> tuple[np.ndarray, np.ndarray]:
    features, labels = [], []
    with path.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            try:
                h = float(row["H"])
                umbrella = float(int(row["UMB"]))
                mean = float(row["HMEAN"])
                delta = float(row["DH"])
                label = float(int(row["LABEL"]))
            except (KeyError, TypeError, ValueError):
                continue
            if (not all(math.isfinite(v) for v in (h, umbrella, mean, delta, label))
                    or not 0.0 <= h <= 100.0 or not 0.0 <= mean <= 100.0
                    or umbrella not in (0.0, 1.0) or label not in (0.0, 1.0)
                    or not math.isclose(delta, h - mean, abs_tol=0.05)):
                continue
            features.append([(h / 100.0 - 0.5) * 2.0, umbrella,
                             (mean / 100.0 - 0.5) * 2.0, delta / 50.0])
            labels.append(label)
    if not features:
        raise ValueError("dataset has no valid rows")
    if len(set(labels)) < 2:
        raise ValueError("dataset must contain both dry (0) and wet (1) samples")
    return np.asarray(features, dtype=np.float32), np.asarray(labels, dtype=np.float32)


# 기능: 모델의 선형 점수를 0~1 확률로 변환합니다.
# 입력: z: NumPy 선형 점수 배열.
# 출력: 원 배열 형태의 확률 배열.
# 처리 구조: 지수 overflow를 줄이도록 z를 -20~20으로 제한한 뒤 logistic 함수를 계산합니다.
def sigmoid(z: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-np.clip(z, -20.0, 20.0)))


# 기능: 로지스틱 회귀의 가중치와 bias를 gradient descent로 학습합니다.
# 입력: x: feature, y: dry/wet label, learning_rate: 양의 학습률, epochs: 반복 수.
# 출력: 4개 가중치와 float bias.
# 처리 구조: 파라미터를 검사하고 예측→오차→평균 gradient→계수 갱신을 반복하며 loss와 accuracy를 출력합니다.
def train(x: np.ndarray, y: np.ndarray, learning_rate: float, epochs: int):
    if not math.isfinite(learning_rate) or learning_rate <= 0 or epochs <= 0:
        raise ValueError("learning rate and epochs must be positive and finite")
    weights = np.zeros(x.shape[1], dtype=np.float32)
    bias = np.float32(0.0)
    for epoch in range(epochs):
        probability = sigmoid(x @ weights + bias)
        error = probability - y
        weights -= learning_rate * (x.T @ error / len(y))
        bias -= learning_rate * np.mean(error)
        if epoch == 0 or (epoch + 1) % 200 == 0:
            loss = -np.mean(y * np.log(probability + 1e-7) +
                            (1.0 - y) * np.log(1.0 - probability + 1e-7))
            accuracy = np.mean((probability > 0.5) == y)
            print(f"epoch={epoch + 1:4d} loss={loss:.4f} accuracy={accuracy:.3f}")
    return weights, float(bias)


# 기능: 학습한 모델 계수를 STM32에서 include할 C 헤더로 저장합니다.
# 입력: path: 출력 헤더 경로, weights: feature 계수, bias: 절편.
# 출력: WET_W0~WET_W3와 WET_BIAS를 정의한 텍스트 파일.
# 처리 구조: include guard와 float 상수를 같은 형식으로 출력해 Python 학습 결과를 C 추론 코드로 연결합니다.
def export_header(path: Path, weights: np.ndarray, bias: float) -> None:
    lines = [
        "/* Generated by ml/train_wet_model.py. */",
        "#ifndef WET_MODEL_PARAMS_H",
        "#define WET_MODEL_PARAMS_H",
        *[f"#define WET_W{i} {value:.8f}f" for i, value in enumerate(weights)],
        f"#define WET_BIAS {bias:.8f}f",
        "/* Runtime hysteresis thresholds are defined in control_logic.c. */",
        "#endif",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


# 기능: CSV 학습부터 C 헤더 출력까지 CLI 흐름을 실행합니다.
# 입력: data/output 경로, 학습률, epochs 옵션.
# 출력: 학습 로그와 모델 계수 헤더.
# 처리 구조: CLI 파싱→load_dataset→train→export_header 순서로 처리합니다.
def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, default=Path("wet_dataset.csv"))
    parser.add_argument("--output", type=Path, default=Path(
        "../firmware/master/Core/Inc/wet_model_params.h"))
    parser.add_argument("--learning-rate", type=float, default=0.01)
    parser.add_argument("--epochs", type=int, default=2000)
    args = parser.parse_args()
    x, y = load_dataset(args.data)
    weights, bias = train(x, y, args.learning_rate, args.epochs)
    export_header(args.output, weights, bias)
    print(f"exported {args.output}")


if __name__ == "__main__":
    main()
